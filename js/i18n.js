    function closeLanguageMenus(except) {
        document.querySelectorAll('.sget-language-menu.open').forEach(menu => { if (!except || menu !== except) menu.classList.remove('open'); });
    }

    function createCustomSelector(control) {
        if (!control || control.dataset.customLanguageReady === '1') return;
        ensureSelectorStyles();
        const wrap = document.createElement('div');
        wrap.className = 'sget-language-wrap';
        control.classList.add('sget-language-native');
        control.parentNode.insertBefore(wrap, control);
        wrap.appendChild(control);

        const btn = document.createElement('button');
        btn.type = 'button';
        btn.className = 'sget-language-btn';
        btn.setAttribute('aria-haspopup', 'listbox');
        btn.setAttribute('aria-expanded', 'false');
        btn.setAttribute('aria-label', 'Language');

        const menu = document.createElement('div');
        menu.className = 'sget-language-menu';
        menu.setAttribute('role', 'listbox');

        [{value:'es',code:'ESP'},{value:'en',code:'ENG'}].forEach(opt => {
            const item = document.createElement('button');
            item.type = 'button'; item.className = 'sget-language-option'; item.dataset.value = opt.value; item.setAttribute('role', 'option');
            item.innerHTML = `${flagSvg(opt.value)}<span>${opt.code}</span>`;
            item.addEventListener('click', e => { e.preventDefault(); control.value = opt.value; closeLanguageMenus(); btn.setAttribute('aria-expanded','false'); setLanguage(opt.value); });
            menu.appendChild(item);
        });
        btn.addEventListener('click', e => { e.preventDefault(); const open = !menu.classList.contains('open'); closeLanguageMenus(menu); menu.classList.toggle('open', open); btn.setAttribute('aria-expanded', open ? 'true' : 'false'); });
        document.addEventListener('click', e => { if (!wrap.contains(e.target)) { menu.classList.remove('open'); btn.setAttribute('aria-expanded','false'); } });
        wrap.append(btn, menu);
        control.dataset.customLanguageReady = '1';
        control._sgetCustom = {btn, menu};
        updateCustomSelector(control, control.value || 'es');
    }

    function updateCustomSelector(control, lang) {
        const ui = control?._sgetCustom;
        if (!ui) return;
        const code = lang === 'en' ? 'ENG' : 'ESP';
        ui.btn.innerHTML = `<span class="sget-language-label">${flagSvg(lang === 'en' ? 'en' : 'es')}<span>${code}</span></span><span class="sget-language-arrow">▾</span>`;
        ui.menu.querySelectorAll('.sget-language-option').forEach(item => item.classList.toggle('active', item.dataset.value === lang));
        ui.btn.title = lang === 'en' ? 'Language: English' : 'Idioma: Español';
    }

    function syncSelectors(lang) {
        document.querySelectorAll('[data-sget-language]').forEach(control => {
            control.value = lang;
            if (control.tagName === 'SELECT') {
                const esOption = control.querySelector('option[value="es"]');
                const enOption = control.querySelector('option[value="en"]');
                if (esOption) esOption.textContent = 'ESP';
                if (enOption) enOption.textContent = 'ENG';
                createCustomSelector(control);
                updateCustomSelector(control, lang);
            }
        });
    }

    function bindControls() {
        document.querySelectorAll('[data-sget-language]').forEach(control => {
            if (control.dataset.sgetBound === '1') return;
            control.dataset.sgetBound = '1';
            control.addEventListener('change', () => setLanguage(control.value));
        });
    }

    window.SGET_I18N = { setLanguage, translateDOM, translateText, syncSelectors, state, t: text => translateText(text, state.current) };

    document.addEventListener('DOMContentLoaded', () => {
        // The server session is authoritative. localStorage is only a fallback for pages
        // that do not expose the server-side language attribute.
        state.current = document.documentElement.getAttribute('data-language') || localStorage.getItem('sget_language') || 'es';
        localStorage.setItem('sget_language', state.current);
        bindControls();
        syncSelectors(state.current);
        applyLocalizedPlaceholders(document, state.current);
        installObserver();
        if (state.current === 'en') translateDOM('en');
    });
