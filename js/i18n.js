    function applyLocalizedPlaceholders(root, lang = state.current) {
        if (!root) return;
        const elements = [];
        if (root.nodeType === Node.ELEMENT_NODE && (root.hasAttribute('data-i18n-placeholder-es') || root.hasAttribute('data-i18n-placeholder-en'))) {
            elements.push(root);
        }
        if (root.querySelectorAll) {
            root.querySelectorAll('[data-i18n-placeholder-es], [data-i18n-placeholder-en]').forEach(el => elements.push(el));
        }
        elements.forEach(el => {
            const es = el.getAttribute('data-i18n-placeholder-es');
            const en = el.getAttribute('data-i18n-placeholder-en');
            if (lang === 'en' && en != null) el.setAttribute('placeholder', en);
            else if (lang === 'es' && es != null) el.setAttribute('placeholder', es);
        });
    }

    function translateAttributes(root) {
        applyLocalizedPlaceholders(root, state.current);
        const attrs = ['title', 'aria-label', 'alt', 'value'];
        const elements = root.querySelectorAll ? root.querySelectorAll('*') : [];
        elements.forEach(el => attrs.forEach(attr => {
            if (el.hasAttribute(attr)) {
                const current = el.getAttribute(attr);
                const translated = state.current === 'en' ? translateText(current) : current;
                if (translated !== current) el.setAttribute(attr, translated);
            }
        }));
    }

    function translateDOM(lang = state.current) {
        if (lang !== 'en') return;
        const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
        const nodes = [];
        let node;
        while ((node = walker.nextNode())) nodes.push(node);
        nodes.forEach(textNode => {
            const parent = textNode.parentElement;
            if (!parent || ['SCRIPT', 'STYLE', 'NOSCRIPT'].includes(parent.tagName)) return;
            const translated = translateText(textNode.nodeValue, lang);
            if (translated !== textNode.nodeValue) textNode.nodeValue = translated;
        });
        translateAttributes(document);
        if (document.title) document.title = translateText(document.title, 'en');
        document.documentElement.setAttribute('lang', 'en');
        document.documentElement.setAttribute('data-language', 'en');
    }

    function installObserver() {
        if (window.__SGET_I18N_OBSERVER__) return;
        window.__SGET_I18N_OBSERVER__ = new MutationObserver(mutations => {
            mutations.forEach(mutation => mutation.addedNodes.forEach(node => {
                if (node.nodeType === Node.TEXT_NODE) {
                    if (state.current === 'en' && node.parentElement && !['SCRIPT', 'STYLE', 'NOSCRIPT'].includes(node.parentElement.tagName)) {
                        node.nodeValue = translateText(node.nodeValue);
                    }
                } else if (node.nodeType === Node.ELEMENT_NODE) {
                    if (state.current === 'en') {
                        const walker = document.createTreeWalker(node, NodeFilter.SHOW_TEXT);
                        const textNodes = [];
                        let t;
                        while ((t = walker.nextNode())) textNodes.push(t);
                        textNodes.forEach(x => {
                            if (!['SCRIPT', 'STYLE', 'NOSCRIPT'].includes(x.parentElement?.tagName)) x.nodeValue = translateText(x.nodeValue);
                        });
                    }
                    // Placeholders must be localized in BOTH languages, including dynamically inserted forms/modals.
                    applyLocalizedPlaceholders(node, state.current);
                    if (state.current === 'en') translateAttributes(node);
                }
            }));
        });
        window.__SGET_I18N_OBSERVER__.observe(document.body, { childList: true, subtree: true });
    }

    async function setLanguage(lang) {
        if (!['es', 'en'].includes(lang)) return;
        try {
            const url = window.SGET_LANGUAGE_URL || 'set_language.php';
            await fetch(url, {
                method: 'POST',
                headers: {'Content-Type': 'application/x-www-form-urlencoded; charset=UTF-8'},
                body: new URLSearchParams({ idioma: lang }).toString(),
                credentials: 'same-origin'
            });
        } catch (e) {
            console.warn('Language preference could not be saved locally.');
        }
        localStorage.setItem('sget_language', lang);
        state.current = lang;
        if (lang === 'en') {
            document.documentElement.setAttribute('data-language', 'en');
            applyLocalizedPlaceholders(document, 'en');
            translateDOM('en');
            installObserver();
            syncSelectors('en');
            if (typeof window.inicializarBotonGoogle === 'function') {
                document.querySelectorAll('[id=panelLogin], [id=panelRegistro]').forEach(panel => {
                    try { window.inicializarBotonGoogle(panel); } catch (_) {}
                });
            }
        } else {
            window.location.reload();
        }
    }

